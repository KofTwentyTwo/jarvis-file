async function writeFavicon(dest, config) {
   const primary = config.theme.primaryColor;
   const accent = config.theme.accentColor;
   const letter = config.project.logoLetter;
   const svg = `<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 100 100">
  <defs>
    <linearGradient id="g" x1="0%" y1="0%" x2="100%" y2="100%">
      <stop offset="0%" style="stop-color:${primary}"/>
      <stop offset="100%" style="stop-color:${accent}"/>
    </linearGradient>
  </defs>
  <rect width="100" height="100" rx="20" fill="url(#g)"/>
  <text x="50" y="68" font-family="Inter,sans-serif" font-size="60" font-weight="700" fill="white" text-anchor="middle">${letter}</text>
</svg>`;
   await fs.writeFile(dest, svg);
}

